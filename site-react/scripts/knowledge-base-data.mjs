export function articleBySlug(slug) {
  return knowledgeArticles.find((article) => article.slug === slug);
}

export function relatedArticlesFor(article) {
  const sameCategory = knowledgeArticles.filter((item) => item.categoryId === article.categoryId && item.slug !== article.slug);
  const others = knowledgeArticles.filter((item) => item.categoryId !== article.categoryId);
  return [...sameCategory, ...others].slice(0, 3);
}

